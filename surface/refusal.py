@dataclass(frozen=True)
class Refusal:
    code: RefusalCode
    detail: str  # specific, human-readable -- "why THIS request", not the generic category description
    context: dict[str, Any] = field(default_factory=dict)  # structured facts for the audit trail

    @property
    def category(self) -> RefusalCategory:
        return _CATEGORY_OF[self.code]

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code.value,
            "category": self.category.value,
            "detail": self.detail,
            "context": self.context,
        }


def refusal_codes_table() -> list[dict[str, str]]:
    """Row data for docs/refusal_codes.md -- generated from this enum, not
    hand-maintained, so the doc can't drift from the code."""
    return [
        {"code": code.value, "category": _CATEGORY_OF[code].value, "description": _DESCRIPTION_OF[code]}
        for code in RefusalCode
    ]
