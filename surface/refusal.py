"""
Structured refusal taxonomy -- Tier 1 safety module.

NO LLM IMPORTS IN THIS FILE (see CLAUDE.md). Every refusal is a fixed,
machine-readable code plus a human-readable detail string; nothing here is
generated, only selected from the fixed set below and filled in with the
specific context that triggered it.

"Refusals are logged as richly as successes" -- a Refusal carries enough
structured context (in `context`) to reconstruct exactly why a transaction
was refused without needing to re-run anything, which is the actual point:
an audit trail that answers "why did the agent get refused" without
guessing.

Twelve codes across six categories -- see docs/refusal_codes.md for the
full table (regenerated by refusal_codes_table(), not hand-maintained, so
the doc can never drift from the enum).
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class RefusalCategory(str, Enum):
    AUTH = "auth"
    POLICY = "policy"
    COMPATIBILITY = "compatibility"
    AVAILABILITY = "availability"
    INTEGRITY = "integrity"
    INFRASTRUCTURE = "infrastructure"


class RefusalCode(str, Enum):
    # --- auth: the Intent Mandate itself doesn't check out ---
    INVALID_SIGNATURE = "invalid_signature"
    MANDATE_EXPIRED = "mandate_expired"

    # --- policy: the mandate checks out, but the request violates its own stated limits ---
    OVER_PRICE_CEILING = "over_price_ceiling"
    CUMULATIVE_CEILING_EXCEEDED = "cumulative_ceiling_exceeded"
    CATEGORY_NOT_ALLOWED = "category_not_allowed"

    # --- compatibility: a requested item's fit-for-purpose claim doesn't hold up ---
    INCOMPATIBLE_ITEM = "incompatible_item"
    UNVERIFIED_COMPATIBILITY = "unverified_compatibility"

    # --- availability: the item isn't there to sell, or isn't safe to sell ---
    OUT_OF_STOCK = "out_of_stock"
    SKU_NOT_PUBLISHED = "sku_not_published"

    # --- integrity: something that should be internally consistent isn't ---
    NONCE_REPLAYED = "nonce_replayed"
    CART_TOTAL_MISMATCH = "cart_total_mismatch"

    # --- infrastructure: the failure is ours, not the request's ---
    PAYMENT_PROVIDER_ERROR = "payment_provider_error"
    INTERNAL_ERROR = "internal_error"


